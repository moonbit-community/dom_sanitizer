// Development-only source extraction. Runtime builds never execute this file.
import fs from 'node:fs';
import { JSDOM } from 'jsdom';
import createDOMPurify from 'dompurify';
const window = new JSDOM('').window;
if (createDOMPurify(window).version !== '3.3.3') throw new Error('Expected DOMPurify 3.3.3');
if (JSON.parse(fs.readFileSync('node_modules/jsdom/package.json')).version !== '29.0.1') throw new Error('Expected jsdom 29.0.1');
const source = fs.readFileSync('node_modules/dompurify/dist/purify.cjs.js', 'utf8');
const tables = {
  html_tags: 'html$1', svg_tags: 'svg$1', svg_filter_tags: 'svgFilters', svg_disallowed_tags: 'svgDisallowed',
  mathml_tags: 'mathMl$1', mathml_disallowed_tags: 'mathMlDisallowed',
  html_attributes: 'html', svg_attributes: 'svg', mathml_attributes: 'mathMl', xml_attributes: 'xml',
  default_forbid_contents: 'DEFAULT_FORBID_CONTENTS', default_data_uri_tags: 'DEFAULT_DATA_URI_TAGS', default_uri_safe_attributes: 'DEFAULT_URI_SAFE_ATTRIBUTES',
};
const header = '// Adapted from DOMPurify 3.3.3 (src/tags.ts, src/attrs.ts, src/purify.ts).\n// Copyright 2025 Dr.-Ing. Mario Heiderich, Cure53. Apache-2.0.\n// See THIRD_PARTY_NOTICES and LICENSE. Generated by tools/generate-policy.mjs.\n\n';
const emit = (name, values) => `///|\nlet ${name} : Set[String] = Set([\n${values.map(v => `  ${JSON.stringify(v)},`).join('\n')}\n])\n\n`;
let out = header;
for (const [name, symbol] of Object.entries(tables)) {
  const line = source.split('\n').find(s => s.trimStart().startsWith(`const ${symbol} = `));
  if (!line) throw new Error(symbol);
  const list = line.slice(line.indexOf('['), line.lastIndexOf(']') + 1);
  const values = Array.from(list.matchAll(/'([^']*)'/g), m => m[1].toLowerCase());
  out += emit(name, [...new Set(values)]);
}
fs.writeFileSync('policy_data.mbt', out);
const doc = window.document.createElement('template').content.ownerDocument;
const names = new Set();
for (let object of [doc, doc.createElement('form')]) {
  while (object !== null) {
    for (const name of Object.getOwnPropertyNames(object)) names.add(name);
    object = Object.getPrototypeOf(object);
  }
}
fs.writeFileSync('dom_names.mbt', '// Fixed document/form property names from jsdom 29.0.1, including inherited names.\n// Generated by tools/generate-policy.mjs; no runtime DOM queries.\n\n' + emit('reserved_dom_names', [...names].sort()));
window.close();
